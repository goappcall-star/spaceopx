import { rolldown } from "rolldown";
import { mkdir, writeFile, readFile, readdir, unlink } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { adaptRnnoiseForWorklet } from "./rnnoise-worklet-adapter.mjs";

export async function buildAudioWorklet() {
  const bundle = await rolldown({
    input: "src/audio/rnnoise-processor.mjs",
    plugins: [
      {
        name: "rnnoise-worklet-environment",
        transform(code, id) {
          if (id.replaceAll("\\", "/").endsWith("/@shiguredo/rnnoise-wasm/dist/rnnoise.js"))
            return adaptRnnoiseForWorklet(code);
        },
      },
    ],
  });
  const result = await bundle.generate({ format: "esm", minify: true });
  await bundle.close();
  const code = result.output[0].code;
  const hash = createHash("sha256").update(code).digest("hex").slice(0, 12);
  await mkdir("public/audio", { recursive: true });
  await mkdir("src/generated", { recursive: true });
  await writeFile(`public/audio/rnnoise-${hash}.js`, code);
  // Keep only the current generated bundle; otherwise desktop installers retain
  // obsolete embedded models. No source files or other public assets are removed.
  const audioRoot = path.resolve("public/audio");
  for (const name of await readdir(audioRoot)) {
    if (/^rnnoise-[a-f0-9]{12}\.js$/.test(name) && name !== `rnnoise-${hash}.js`) {
      const generatedPath = path.resolve(audioRoot, name);
      if (!generatedPath.startsWith(audioRoot + path.sep)) throw Error("Unexpected generated path");
      await unlink(generatedPath);
    }
  }
  await writeFile(
    "src/generated/audio-worklet.ts",
    `// Generated by scripts/build-audio-worklet.mjs\nexport const RNNOISE_WORKLET_URL = "/audio/rnnoise-${hash}.js";\n`,
  );
  // Preserve the upstream wrapper and RNNoise notices in both distributions.
  const notice = await readFile("node_modules/@shiguredo/rnnoise-wasm/LICENSE", "utf8");
  await writeFile("public/audio/LICENSE-rnnoise-wasm.txt", notice);
}
