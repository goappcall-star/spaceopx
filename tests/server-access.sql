BEGIN;
SET LOCAL ROLE authenticated;
SELECT community_test.actor(1);
CREATE TEMP TABLE setup_servers AS SELECT public.create_server_with_options('Novo squad','Descrição curta',NULL,'public','gaming') AS id;
SELECT community_test.assert((SELECT visibility='public' AND theme='gaming' AND owner_id=auth.uid() FROM public.servers WHERE id=(SELECT id FROM setup_servers)),'creation saves options');
SELECT community_test.assert((SELECT count(*)=3 FROM public.roles WHERE server_id=(SELECT id FROM setup_servers)),'existing three roles preserved');
SELECT community_test.assert((SELECT count(*)=1 FROM public.channels WHERE server_id=(SELECT id FROM setup_servers) AND name='geral'),'existing geral channel preserved');
SELECT community_test.assert((SELECT count(*)=1 FROM public.member_roles mr JOIN public.server_members m ON m.id=mr.member_id JOIN public.roles r ON r.id=mr.role_id WHERE m.server_id=(SELECT id FROM setup_servers) AND m.user_id=auth.uid() AND r.name='OWNER'),'creator keeps OWNER membership');
CREATE TEMP TABLE legacy_setup AS SELECT public.create_server('Legacy server') AS id;
SELECT community_test.assert((SELECT visibility='private' AND theme='other' FROM public.servers WHERE id=(SELECT id FROM legacy_setup)),'legacy creation keeps defaults');
SELECT community_test.denied($sql$SELECT public.create_server_with_options('Invalid',NULL,NULL,'unsafe','gaming')$sql$,'22023');
SELECT community_test.denied($sql$SELECT public.create_server_with_options('Invalid',NULL,NULL,'private','invalid')$sql$,'22023');
SELECT community_test.actor(2);
SELECT community_test.assert((SELECT count(*)=0 FROM public.channels WHERE server_id=(SELECT id FROM setup_servers)),'public visibility does not expose private channels to nonmembers');
SET LOCAL ROLE anon;
SELECT community_test.denied($sql$SELECT public.create_server_with_options('Anonymous')$sql$,'42501');
RESET ROLE;
SAVEPOINT failed_setup;
CREATE FUNCTION community_test.reject_setup_options() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.theme='art' THEN RAISE EXCEPTION 'synthetic_setup_failure'; END IF; RETURN NEW; END $$;
CREATE TRIGGER synthetic_setup_failure BEFORE UPDATE ON public.servers FOR EACH ROW EXECUTE FUNCTION community_test.reject_setup_options();
SET LOCAL ROLE authenticated;
SELECT community_test.actor(1);
SELECT community_test.denied($sql$SELECT public.create_server_with_options('Must roll back',NULL,NULL,'private','art')$sql$,'P0001','synthetic_setup_failure');
SELECT community_test.assert(NOT EXISTS(SELECT 1 FROM public.servers WHERE name='Must roll back'),'failed options roll back the entire existing creation flow');
ROLLBACK TO SAVEPOINT failed_setup;
ROLLBACK;
